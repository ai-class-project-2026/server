def _as_list(value, kind):
    if value is None:
        return None
    if isinstance(value, kind):
        return [value]
    return list(value)


def _check(text, want_dates, want_times, want_texts, ref):
    mentions = parse(text, ref)
    got_dates = [m.date for m in mentions if m.date]
    ok = got_dates == want_dates
    detail = f"날짜 {want_dates} / {got_dates}"
    if want_times is not None:
        got_times = [m.time for m in mentions if m.time]
        ok = ok and got_times == want_times
        detail += f", 시각 {want_times} / {got_times}"
    if want_texts is not None:
        got_texts = [m.time_text for m in mentions if m.time_text]
        ok = ok and got_texts == want_texts
        detail += f", 시각문구 {want_texts} / {got_texts}"
    return ok, detail


def main():
    if len(EXAMPLES) < 100:
        print(f"✗ 예시 {len(EXAMPLES)}개. 100개 이상이어야 한다.")
        return 1
    ok = 0
    for row in EXAMPLES:
        text, dates = row[0], row[1]
        times = row[2] if len(row) > 2 else None
        texts = row[3] if len(row) > 3 else None
        passed, detail = _check(
            text,
            _as_list(dates, dt.date),
            _as_list(times, dt.time),
            _as_list(texts, str),
            REF,
        )
        ok += passed
        if not passed:
            print(f"✗ {text!r}: {detail}")
    print(f"\n{ok}/{len(EXAMPLES)} 정답")

    span_ok = 0
    for text, want in SPAN_CHECKS:
        got = [(m.start, m.end, m.date, m.time, m.time_text) for m in parse(text, REF)]
        span_ok += got == want
        if got != want:
            print(f"✗ span {text!r}: 정답 {want}, 결과 {got}")
    print(f"{span_ok}/{len(SPAN_CHECKS)} 위치 정답")

    other_ok = 0
    for text, ref, want in OTHER:
        got = [m.date for m in parse(text, ref) if m.date]
        other_ok += got == want
        if got != want:
            print(f"✗ 기준일 {ref} {text!r}: 정답 {want}, 결과 {got}")
    print(f"{other_ok}/{len(OTHER)} 다른 기준일 정답")
    return 0 if ok == len(EXAMPLES) and span_ok == len(SPAN_CHECKS) and other_ok == len(OTHER) else 1


if __name__ == "__main__":
    sys.exit(main())
