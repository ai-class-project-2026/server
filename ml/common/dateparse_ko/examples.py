def _as_list(value, kind):
    if value is None:
        return None
    if isinstance(value, kind):
        return [value]
    return list(value)


def _dates_ok(mentions, want):
    """정답 날짜가 순서대로 모두 나와야 한다. 한 글자 요일의 tentative 후보는 정답에 없어도 된다
    (명사로 쓰인 "목 아파"는 없거나 tentative여야 하고, 확정 날짜로 나오면 안 된다)."""
    k = 0
    for m in mentions:
        if not m.date:
            continue
        if k < len(want) and m.date == want[k]:
            k += 1
        elif not m.tentative:
            return False
    return k == len(want)


def _check(text, want_dates, want_times, want_texts, ref):
    mentions = parse(text, ref)
    got_dates = [m.date for m in mentions if m.date]
    ok = _dates_ok(mentions, want_dates)
    detail = f"날짜 {want_dates} / {got_dates}"
    if want_times is not None:
        got_times = [m.time for m in mentions if m.time]
        ok = ok and got_times == want_times
        detail += f", 시각 {want_times} / {got_times}"
    if want_texts is not None:
        got_texts = [m.time_text for m in mentions if m.time_text]
        ok = ok and got_texts == want_texts
        detail += f", 시각문구 {want_texts} / {got_texts}"
    return ok, detail


def main():
    if len(EXAMPLES) < 100:
        print(f"✗ 예시 {len(EXAMPLES)}개. 100개 이상이어야 한다.")
        return 1
    ok = 0
    for row in EXAMPLES:
        text, dates = row[0], row[1]
        times = row[2] if len(row) > 2 else None
        texts = row[3] if len(row) > 3 else None
        passed, detail = _check(
            text,
            _as_list(dates, dt.date),
            _as_list(times, dt.time),
            _as_list(texts, str),
            REF,
        )
        ok += passed
        if not passed:
            print(f"✗ {text!r}: {detail}")
    print(f"\n{ok}/{len(EXAMPLES)} 정답")

    span_ok = 0
    for text, want in SPAN_CHECKS:
        got = [(m.start, m.end, m.date, m.time, m.time_text) for m in parse(text, REF)]
        span_ok += got == want
        if got != want:
            print(f"✗ span {text!r}: 정답 {want}, 결과 {got}")
    print(f"{span_ok}/{len(SPAN_CHECKS)} 위치 정답")

    other_ok = 0
    for text, ref, want in OTHER:
        got = [m.date for m in parse(text, ref) if m.date]
        other_ok += got == want
        if got != want:
            print(f"✗ 기준일 {ref} {text!r}: 정답 {want}, 결과 {got}")
    print(f"{other_ok}/{len(OTHER)} 다른 기준일 정답")
    tent_ok = 0
    for text, want_date, want_flag in TENTATIVE:
        got = [(m.date, m.tentative) for m in parse(text, REF) if m.date]
        tent_ok += got == [(want_date, want_flag)]
        if got != [(want_date, want_flag)]:
            print(f"✗ tentative {text!r}: 정답 {[(want_date, want_flag)]}, 결과 {got}")
    print(f"{tent_ok}/{len(TENTATIVE)} tentative 표시 정답")

    none_ok = 0
    for text in STRICT_NONE:
        got = [m for m in parse(text, REF) if m.date]
        none_ok += not got
        if got:
            print(f"✗ 후보도 아니어야 함 {text!r}: {got}")
    print(f"{none_ok}/{len(STRICT_NONE)} 후보 아님 정답")
    good = (ok == len(EXAMPLES) and span_ok == len(SPAN_CHECKS) and other_ok == len(OTHER)
            and tent_ok == len(TENTATIVE) and none_ok == len(STRICT_NONE))
    return 0 if good else 1


